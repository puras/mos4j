package net.hegq.mos4j.model;

/**
 * 异步任务的刷新器（协议层实现）。
 *
 * <p><b>为什么把「刷新」和「句柄」分开</b>：句柄是跨种类的公共底座（{@link TaskHandle}），
 * 而「怎么查这个任务是各家私有的」（轮询端点、状态字段名、终态取值都不一样）——所以
 * 协议层提供一个实现，种类层只管用。
 *
 * <p><b>为什么不做成带退避的循环</b>：轮询节奏是宿主的策略（多久查一次、查多久、
 * 查不到算不算超时），不该由框架偷偷定。框架只提供「刷新一次」这个原子动作，
 * 退避与超时留给上层——和取消语义一致：框架不替宿主做决定。
 */
public interface TaskPoller {

    /**
     * 刷新一次任务状态。
     *
     * @param handle 当前句柄（至少要有任务号）
     * @return 刷新后的句柄（状态可能没变）
     */
    TaskHandle refresh(TaskHandle handle);
}
