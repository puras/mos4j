package net.hegq.mos4j.context;

/**
 * 压缩失败策略（压缩失败时本轮怎么办）。
 *
 * <p><b>为什么要有这个开关</b>：压缩是为了<em>继续对话</em>的机制。压缩失败说明摘要没做出来，
 * 而上下文可能已经超预算——下一次模型调用可能被服务商直接拒收。两种收尾都诚实：
 * 终止并说清「压缩失败」，比硬撑着发一个必然溢出的请求好。
 * 但有些宿主宁可带着超预算继续跑（例如自己知道模型还有余量），所以把决定权交出去。
 *
 * <p><b>与 Go 参考版的有意差异</b>：Go 在「跳过并继续」时会往会话日志写一条
 * {@code compaction} 事件，失败原因放在 {@code failed} 字段里。Java 的
 * <b>事件字段冻结清单里没有 {@code failed}</b>（80 条 / 71 名，摘要
 * {@code 3d35911d…}），加字段会破冻结基线；而写一条没有失败原因的半截压缩事件，
 * 会让投影误以为「历史被遮蔽了但没摘要」——比不写更糟。
 * 因此 Java <b>不写该事件</b>：失败原因只通过 {@code onCompactionFailure} 回调交给宿主，
 * 会话日志里「这轮没压缩」就是事实。
 *
 * @see CompactionService
 */
public enum CompactionFailurePolicy {

    /**
     * 压缩失败即终止本轮（<b>默认</b>，fail-closed）。
     *
     * <p>压缩失败时抛出异常，驱动先写 {@code turn/end{error}} 再抛给宿主：
     * 历史没被遮蔽（事实还在日志里），但本轮以错误收尾，不留下孤儿轮次。
     */
    FAIL_CLOSED,

    /**
     * 压缩失败 → 跳过压缩，本轮继续。
     *
     * <p>上下文可能已经超预算——<b>是否承担这个风险由宿主决定</b>（本策略不默认启用）。
     * 失败原因通过 {@code onCompactionFailure} 回调交给宿主（不回调就是宿主不关心）。
     */
    SKIP_AND_CONTINUE
}
